#!/usr/bin/env python3
"""Builds angel-of-the-hour.html and assets/angels-data.js from tools/angels_data.py.
Standard library only. Run: python3 tools/build_angels.py"""
import html
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from angels_data import SEVEN, PAULINA, PAULINA_RULE, PLANETS  # noqa: E402

DAY_RULER = ['Sun', 'Moon', 'Mars', 'Mercury', 'Jupiter', 'Venus', 'Saturn']  # Sunday..Saturday
WEEKDAYS = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday']
GLYPH = {'Saturn': '♄', 'Jupiter': '♃', 'Mars': '♂', 'Sun': '☉', 'Venus': '♀', 'Mercury': '☿', 'Moon': '☽'}
ORD = ['first', 'second', 'third', 'fourth', 'fifth', 'sixth', 'seventh', 'eighth', 'ninth', 'tenth', 'eleventh', 'twelfth']
ROMAN = ['I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII']
ARS_PAULINA_APP = 'https://play.google.com/store/apps/details?id=com.discoveryscience.arspaulina'
ANGEL_APP = {'Sun': 'michael', 'Moon': 'gabriel', 'Mars': 'samael', 'Mercury': 'raphael', 'Jupiter': 'sachiel', 'Venus': 'anael', 'Saturn': 'cassiel'}


def e(s):
    return html.escape(s, quote=True)


def the(planet):
    return 'the ' + planet if planet in ('Sun', 'Moon') else planet


def slug(name):
    return name.lower().replace(' ', '-')


def served(index):  # index 0..23 -> planet served on each weekday
    return [PLANETS[(PLANETS.index(DAY_RULER[wd]) + index) % 7] for wd in range(7)]


# dukes named under more than one angel
duke_home = {}
for period, no, hname, angel, retinue, dukes, note in PAULINA:
    for d in dukes:
        duke_home.setdefault(d, []).append(angel)
shared = {d: a for d, a in duke_home.items() if len(set(a)) > 1}

# ------------------------------------------------------------------ data for the browser
data = {
    'seven': {p: {'angel': v['angel'], 'slug': v['slug'], 'day': v['day'], 'hebrew': v.get('hebrew'),
                  'hebrewLabel': v.get('hebrew_label'), 'quarters': v['quarters'], 'app': ANGEL_APP[p]}
              for p, v in SEVEN.items()},
    'paulina': [{'period': p, 'no': n, 'hour': h, 'angel': a, 'slug': 'paulina-' + slug(a), 'retinue': r, 'dukes': len(d)}
                for p, n, h, a, r, d, _ in PAULINA],
}
# the city list is shared with the Planetary Hour Now tool so both pages offer the same places
import re  # noqa: E402
hn = open(os.path.join(ROOT, 'assets', 'hour-now.js'), encoding='utf-8').read()
block = hn[hn.index('var CITIES = [') + len('var CITIES = '):hn.index('].sort(') + 1]
cities = sorted(json.loads(re.sub(r"'", '"', block)), key=lambda c: c[0])
with open(os.path.join(ROOT, 'assets', 'angels-data.js'), 'w', encoding='utf-8') as fh:
    fh.write('/* Generated by tools/build_angels.py from tools/angels_data.py. Do not edit by hand. */\n')
    fh.write('window.DS_ANGELS = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
    fh.write('window.DS_CITIES = ' + json.dumps(cities, ensure_ascii=False, separators=(',', ':')) + ';\n')

# ------------------------------------------------------------------ codex HTML
seven_html = []
for planet in ['Sun', 'Moon', 'Mars', 'Mercury', 'Jupiter', 'Venus', 'Saturn']:
    v = SEVEN[planet]
    art = {'name': v['angel'], 'planet': planet, 'hebrew': v.get('hebrew'), 'kind': 'day', 'lite': True, 'subtitle': v['angel'],
           'ring': f"{v['angel'].upper()} ✦ ANGEL OF {the(planet).upper()} ✦ {v['day'].upper()} ✦ ",
           'label': f"Devotional artwork of {v['angel']}, angel of {the(planet)}"}
    facts = [('Day', f"{v['day']} · {GLYPH[planet]} {the(planet)}"),
             ('Name', v['angel'] + (f" · {v['hebrew']} ({v['hebrew_label']}, Agrippa)" if v.get('hebrew_label') else f" · {v['hebrew']}") + f" · {v['meaning']}"),
             ('Companions on his day', ', '.join(v['companions'])),
             ('Heaven', f"{v['heaven']}, the {v['heaven_no']}" if v['heaven'] else 'None named for Saturday'),
             ('King of the air', f"{v['air_king']}; ministers {', '.join(v['air_ministers'])}"),
             ('Wind', f"the {v['wind']} wind"),
             ('Perfume of the day', v['perfume'])]
    q = ''
    if v['quarters']:
        q = ('<h4>To be called “from the four parts of the world”</h4><div class="quarters">' +
             ''.join(f'<div><b>{k}</b><span>{e(", ".join(names))}</span></div>' for k, names in v['quarters'].items()) + '</div>')
    else:
        q = '<p class="fine">For the four quarters on ' + v['day'] + ' the Heptameron gives prayers instead of angels.</p>'
    seven_html.append(f'''
<article class="codex reveal" id="angel-{v['slug']}" data-planet="{planet}">
  <div class="codex-art" data-art='{e(json.dumps(art, ensure_ascii=False))}'></div>
  <div class="codex-text">
    <div class="eyebrow">{GLYPH[planet]} {v['day']} · angel of {the(planet)}</div>
    <h3>{v['angel']}</h3>
    {''.join('<p>' + e(p) + '</p>' for p in v['essay'])}
    <dl class="facts">{''.join(f'<dt>{e(a)}</dt><dd>{e(b)}</dd>' for a, b in facts)}</dl>
    {q}
    <p class="note"><span class="tag tr">Agrippa</span> {e(v['agrippa'])}</p>
    <p class="note"><span class="tag tr">Ars Paulina</span> {e(v['paulina'])}</p>
    <p><a class="btn ghost small" href="https://play.google.com/store/apps/details?id=com.discoveryscience.{ANGEL_APP[planet]}" rel="noopener">{e(v['angel'])} on your home screen · Google Play</a></p>
  </div>
</article>''')

paulina_html = []
for i, (period, no, hname, angel, retinue, dukes, note) in enumerate(PAULINA):
    sv = served(i)
    art = {'name': angel, 'planet': 'Sun' if period == 'day' else 'Moon', 'medallion': ROMAN[no-1], 'lite': True, 'kind': 'pauline', 'period': period, 'hour': no, 'subtitle': angel,
           'ring': f"{angel.upper()} ✦ THE {ORD[no-1].upper()} HOUR OF THE {period.upper()} ✦ {hname.upper()} ✦ ",
           'label': f"Devotional artwork of {angel}, angel of the {ORD[no-1]} hour of the {period}"}
    sh = [d for d in dukes if d in shared]
    shared_txt = ''
    if sh:
        shared_txt = '<p class="fine">Dukes who also serve another hour: ' + '; '.join(
            e(d) + ' (also under ' + e(', '.join(sorted(set(shared[d]) - {angel}))) + ')' for d in sh) + '.</p>'
    week = ''.join(f'<td><span class="g" data-p="{p}">{GLYPH[p]}</span> {p}</td>' for p in sv)
    paulina_html.append(f'''
<article class="codex small reveal" id="paulina-{slug(angel)}" data-hour="{i}">
  <div class="codex-art" data-art='{e(json.dumps(art, ensure_ascii=False))}'></div>
  <div class="codex-text">
    <div class="eyebrow">{ROMAN[no-1]} · the {ORD[no-1]} hour of the {period}</div>
    <h3>{e(angel)}</h3>
    <p class="lede2">Ruler of the {ORD[no-1]} hour of every {period}, the hour called <i>{e(hname)}</i>. In the manuscript he has {e(retinue)}.</p>
    {('<p class="note">' + e(note) + '</p>') if note else ''}
    <p>Like every angel of the hours, {e(angel)} has no planet of his own. The Ars Paulina says the offices of these angels change with the day: in his hour he does “all things that are attributed to” whichever planet rules it. Over a week he serves all seven:</p>
    <div class="tablewrap"><table class="data week"><thead><tr>{''.join(f'<th scope="col">{d[:3]}</th>' for d in WEEKDAYS)}</tr></thead><tbody><tr>{week}</tr></tbody></table></div>
    <h4>His chief dukes named in the manuscript</h4>
    <p class="dukes">{e(', '.join(dukes))}</p>
    {shared_txt}
  </div>
</article>''')

FAQ = [
    ('What is the Pauline angel of the hour?', 'The Ars Paulina, the third book of the seventeenth-century Lemegeton, names an angel for each of the twelve hours of the day and the twelve hours of the night, counted from sunrise. The first hour of every day is ruled by Samael, the first hour of every night by Sabrathan.'),
    ('How is the Pauline hour different from the planetary hour?', 'The planetary hour belongs to one of the seven planets and changes with the day of the week. The Pauline angel belongs to the hour’s number and is the same every day. The Ars Paulina joins the two: the angel of the hour does “all things that are attributed to” the planet that rules that hour.'),
    ('Which angel rules today?', 'In the Heptameron each day has an angel: Michael on Sunday, Gabriel on Monday, Samael on Tuesday, Raphael on Wednesday, Sachiel on Thursday, Anael on Friday and Cassiel on Saturday.'),
    ('When does the angel of the day rule the hour too?', 'In the first and eighth hours of the day and the third and tenth hours of the night, the planet of the hour is the planet of the day. These are the hours the Ars Paulina names for its observances on Sunday, Monday, Wednesday and Saturday.'),
    ('Is my location sent anywhere?', 'No. Sunrise, sunset, the hours and the positions of the planets are calculated in your browser.'),
    ('Is the artwork historical?', 'No. The figures and seals on this page are modern devotional artwork made for Discovery Science. The names, hours, numbers and texts come from the sources cited.'),
]
faq_ld = json.dumps({'@context': 'https://schema.org', '@type': 'FAQPage', 'mainEntity': [
    {'@type': 'Question', 'name': q, 'acceptedAnswer': {'@type': 'Answer', 'text': a}} for q, a in FAQ]}, ensure_ascii=False)

tpl = open(os.path.join(HERE, 'templates', 'angel-of-the-hour.src.html'), encoding='utf-8').read()
page = (tpl.replace('{{SEVEN}}', ''.join(seven_html))
           .replace('{{PAULINA}}', ''.join(paulina_html))
           .replace('{{FAQ_JSONLD}}', '<script type="application/ld+json">' + faq_ld + '</script>')
           .replace('{{FAQ_HTML}}', ''.join(f'<dt>{e(q)}</dt><dd>{e(a)}</dd>' for q, a in FAQ))
           .replace('{{RULE}}', e(PAULINA_RULE))
           .replace('{{ARS_PAULINA_APP}}', ARS_PAULINA_APP))
with open(os.path.join(ROOT, 'angel-of-the-hour.html'), 'w', encoding='utf-8') as fh:
    fh.write(page)
print('built angel-of-the-hour.html', len(page), 'bytes;', len(shared), 'dukes shared between hours')
